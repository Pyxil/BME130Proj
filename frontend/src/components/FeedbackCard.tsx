import type { FeedbackResponse } from "../types";
import { Spinner } from "./ui";

export function FeedbackCard({ feedback, loading, error }: { feedback: FeedbackResponse | null; loading: boolean; error?: string | null }) {
  const ai = feedback?.source.startsWith("llm");
  return (
    <section aria-labelledby="ai-rec" className="rounded-2xl bg-brand-50 p-5 ring-1 ring-brand-200 dark:bg-brand-900/30 dark:ring-brand-800">
      <div className="flex flex-wrap items-center justify-between gap-2">
        <h3 id="ai-rec" className="text-lg font-bold text-brand-900 dark:text-brand-100">
          {ai ? "AI recommendation" : "Recommendation"}
        </h3>
        {feedback && (
          <span className="text-xs text-brand-800 dark:text-brand-200">
            {ai ? "Generated by AI from your measured results" : "Generated from your measured results"}
          </span>
        )}
      </div>
      {loading && <div className="mt-3"><Spinner label="Writing personalised tips…" /></div>}
      {error && !loading && <p className="mt-3 text-rose-800 dark:text-rose-200">{error}</p>}
      {feedback && !loading && (
        <div className="mt-3 space-y-3 text-slate-800 dark:text-slate-100">
          <p className="text-lg">{feedback.summary}</p>
          {(feedback.recommendations ?? []).length > 0 && (
            <ul className="space-y-3">
              {(feedback.recommendations ?? []).map((r, i) => (
                <li key={`${r.issue_id}-${i}`} className="rounded-xl bg-white p-4 dark:bg-slate-900">
                  <p className="font-bold">{r.tip}</p>
                  {r.articulation && <p className="mt-1 text-slate-700 dark:text-slate-300">👄 {r.articulation}</p>}
                </li>
              ))}
            </ul>
          )}
          {feedback.progress_note && <p className="font-semibold text-brand-900 dark:text-brand-100">📈 {feedback.progress_note}</p>}
          {feedback.encouragement && <p className="italic">{feedback.encouragement}</p>}
        </div>
      )}
    </section>
  );
}
