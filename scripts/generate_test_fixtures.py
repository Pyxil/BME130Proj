#!/usr/bin/env python3
"""Generate deterministic audio fixtures for pipeline integration tests.

Fixtures are synthesised once with Piper voices (phoneme input, so we can
create *controlled* mispronunciations such as "wabbit" for "rabbit") and then
committed.  VITS synthesis is stochastic, so tests must use the committed WAV
files rather than re-synthesising.

Voices: en_US-libritts_r-medium and en_GB-vctk-medium (both CC BY 4.0).
These recordings are synthetic; they test the pipeline's behaviour, not its
accuracy on real speakers (see docs/validation.md for that).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import soundfile as sf

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from speech_analysis.audio_processing.io import resample  # noqa: E402
from speech_analysis.tts.piper import PiperVoice, arpabet_to_espeak_ipa  # noqa: E402

OUT = ROOT / "speech_analysis" / "tests" / "fixtures"
US = ("en_US-libritts_r-medium", 12)
GB = ("en_GB-vctk-medium", 5)

# name, word, realised ARPAbet, voice, expectation
SPEECH = [
    ("butterfly_correct_us", "butterfly", "B AH1 T ER0 F L AY2", US, {"kind": "correct"}),
    ("butterfly_correct_gb", "butterfly", "B AH1 T AH0 F L AY2", GB, {"kind": "correct", "variant": "gb"}),
    ("butterfly_vowel_error", "butterfly", "B AE1 T ER0 F L AY2", US, {"kind": "error", "position": 1}),
    ("rabbit_correct", "rabbit", "R AE1 B AH0 T", US, {"kind": "correct"}),
    ("rabbit_r_as_w", "rabbit", "W AE1 B AH0 T", US, {"kind": "error", "position": 0}),
    ("leaf_correct", "leaf", "L IY1 F", US, {"kind": "correct"}),
    ("leaf_l_as_w", "leaf", "W IY1 F", US, {"kind": "error", "position": 0}),
    ("spoon_correct", "spoon", "S P UW1 N", US, {"kind": "correct"}),
    ("spoon_cluster_reduced", "spoon", "P UW1 N", US, {"kind": "error", "position": 0}),
    ("banana_correct", "banana", "B AH0 N AE1 N AH0", US, {"kind": "correct"}),
    ("banana_syllable_dropped", "banana", "N AE1 N AH0", US, {"kind": "error", "position": 0}),
    ("strawberry_correct", "strawberry", "S T R AO1 B EH2 R IY0", US, {"kind": "correct"}),
    ("tomato_gb", "tomato", "T AH0 M AA1 T OW2", GB, {"kind": "correct", "variant": "us-2"}),
]


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    voices = {}
    manifest = []
    rng = np.random.default_rng(1234)
    for name, word, arpa, (voice, sid), expect in SPEECH:
        if voice not in voices:
            voices[voice] = PiperVoice.from_dir(ROOT / "models" / "piper" / voice)
        v = voices[voice]
        accent = "gb" if voice.startswith("en_GB") else "us"
        y = v.synthesize_ipa(arpabet_to_espeak_ipa(arpa.split(), accent), speaker_id=sid,
                             noise_scale=0.333, noise_w=0.333)
        y = resample(y, v.sample_rate, 16000) * 0.5
        pad = np.zeros(int(0.35 * 16000), dtype=np.float32)
        y = np.concatenate([pad, y, pad]) + rng.normal(0, 3e-4, size=len(y) + 2 * len(pad)).astype(np.float32)
        sf.write(OUT / f"{name}.wav", y, 16000, subtype="PCM_16")
        manifest.append({"file": f"{name}.wav", "word": word, "realised": arpa, "voice": f"{voice}:{sid}", **expect})

    base, _ = sf.read(OUT / "rabbit_correct.wav", dtype="float32")
    quality = {
        "silence": np.zeros(16000, dtype=np.float32) + rng.normal(0, 2e-4, 16000).astype(np.float32),
        "too_quiet": base * 0.004,
        "clipped": np.clip(base * 40, -1, 1),
        "noisy": base + rng.normal(0, 0.06, size=len(base)).astype(np.float32),
        "truncated_end": base[: int(np.argmax(np.abs(base) > 0.05)) + int(0.2 * 16000)],
    }
    for name, y in quality.items():
        sf.write(OUT / f"quality_{name}.wav", np.clip(y, -1, 1), 16000, subtype="PCM_16")
        manifest.append({"file": f"quality_{name}.wav", "word": "rabbit", "kind": "bad_quality", "quality": name})
    (OUT / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    (OUT / "README.md").write_text(
        "# Test fixtures\n\nSynthetic recordings generated by `scripts/generate_test_fixtures.py` with Piper voices "
        "`en_US-libritts_r-medium` (LibriTTS-R, CC BY 4.0) and `en_GB-vctk-medium` (VCTK, CC BY 4.0). "
        "Mispronunciations are produced by synthesising altered phoneme sequences. See `manifest.json`.\n"
    )
    print(f"wrote {len(manifest)} fixtures to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
