"""Claude provider (official Anthropic Python SDK).

Configuration (environment variables):

* ``ANTHROPIC_API_KEY`` (or ``ANTHROPIC_AUTH_TOKEN`` / an ``ant auth login`` profile)
* ``LLM_MODEL`` - default ``claude-opus-5-5``
* ``LLM_EFFORT`` - default ``low`` (short structured task; keeps feedback fast)
* ``LLM_TIMEOUT_S`` - default 30

Uses structured outputs (JSON schema) so the response is always parseable,
and server-side refusal fallbacks (``fallbacks: "default"``) so a safety
decline is retried on a fallback model inside the same call.
"""

from __future__ import annotations

import logging
import os

from . import ProviderError

log = logging.getLogger(__name__)


class AnthropicProvider:
    name = "anthropic"

    def __init__(self) -> None:
        import anthropic  # optional dependency: pip install -e .[llm]

        self._anthropic = anthropic
        self.model = os.environ.get("LLM_MODEL", "claude-opus-5-5")
        self.effort = os.environ.get("LLM_EFFORT", "low")
        timeout = float(os.environ.get("LLM_TIMEOUT_S", "30"))
        self._client = anthropic.Anthropic(timeout=timeout, max_retries=2)

    def generate(self, system: str, user: str, schema: dict) -> str:
        anthropic = self._anthropic
        try:
            response = self._client.beta.messages.create(
                model=self.model,
                max_tokens=16000,
                betas=["server-side-fallback-2026-07-01"],
                fallbacks="default",
                system=system,
                output_config={"effort": self.effort, "format": {"type": "json_schema", "schema": schema}},
                messages=[{"role": "user", "content": user}],
            )
        except anthropic.AuthenticationError as exc:
            raise ProviderError("Anthropic authentication failed (check ANTHROPIC_API_KEY)") from exc
        except anthropic.PermissionDeniedError as exc:
            raise ProviderError("Anthropic API key lacks permission for this model") from exc
        except anthropic.NotFoundError as exc:
            raise ProviderError(f"model {self.model!r} not found") from exc
        except anthropic.RateLimitError as exc:
            raise ProviderError("rate limited by the Anthropic API") from exc
        except anthropic.BadRequestError as exc:
            raise ProviderError(f"bad request: {exc.message}") from exc
        except anthropic.APIStatusError as exc:
            raise ProviderError(f"Anthropic API error {exc.status_code}") from exc
        except anthropic.APIConnectionError as exc:
            raise ProviderError("could not reach the Anthropic API") from exc

        if response.stop_reason == "refusal":
            category = getattr(response.stop_details, "category", None) if response.stop_details else None
            raise ProviderError(f"model declined the request (category={category})")
        if response.stop_reason == "max_tokens":
            raise ProviderError("response truncated (max_tokens)")
        text = next((b.text for b in response.content if b.type == "text"), None)
        if not text:
            raise ProviderError("empty response")
        log.debug("feedback generated by %s (request %s)", response.model, getattr(response, "_request_id", None))
        return text
